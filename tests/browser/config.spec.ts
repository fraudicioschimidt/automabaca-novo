import { expect, test } from "@playwright/test";
import { prisma } from "@/src/infra/prisma";
import { addAuthenticatedSession } from "./helpers/authenticated-session";
import { coletarErrosDoNavegador, descreverErros } from "./helpers/console-errors";

test("Config preserva criação recusada e espelha a normalização dos aliases", async ({ page, context, baseURL }) => {
  if (!new URL(process.env.DATABASE_URL ?? "").pathname.endsWith("_e2e")) throw new Error("Banco E2E obrigatório.");
  const suffix = `${Date.now()}-${test.info().project.name}`;
  const name = `Tipster qualidade ${suffix}`;
  const canon = `Mercado qualidade ${suffix}`;
  const market = await prisma.mercadoPadrao.create({ data: { nome: canon } });
  await addAuthenticatedSession({ context, baseURL: baseURL! });
  const errors = coletarErrosDoNavegador(page);
  await page.goto("/config", { waitUntil: "networkidle" });
  await page.getByRole("button", { name: "Novo tipster", exact: true }).click();
  await page.getByPlaceholder("Nome do tipster").fill(name);
  await page.getByPlaceholder("-100...").fill("inválido");
  await page.getByRole("button", { name: "Adicionar", exact: true }).click();
  await expect(page.getByText(/channelId inválido/)).toBeVisible();
  await expect(page.getByPlaceholder("Nome do tipster")).toHaveValue(name);
  expect(await prisma.bankroll.count({ where: { nome: name } })).toBe(0);
  await page.getByPlaceholder("-100...").fill("");
  await page.getByRole("button", { name: "Adicionar", exact: true }).click();
  await expect(page.getByRole("button", { name: `Editar ${name}`, exact: true })).toBeVisible();
  expect(await prisma.bankroll.count({ where: { nome: name } })).toBe(1);
  await page.getByRole("tab", { name: /^Mercados/ }).click();
  await page.getByRole("textbox", { name: "Buscar mercado ou alias" }).fill(canon);
  const add = page.getByRole("button", { name: "alias", exact: true });
  await add.click();
  await page.getByPlaceholder("novo alias…").fill("Vencedor do jogo");
  await page.getByPlaceholder("novo alias…").press("Enter");
  await expect(page.getByRole("button", { name: `Remover alias Vencedor do jogo de ${canon}`, exact: true })).toBeVisible();
  await add.click();
  await page.getByPlaceholder("novo alias…").fill("vencedor DO jogo");
  await page.getByPlaceholder("novo alias…").press("Enter");
  const remove = page.getByRole("button", { name: `Remover alias vencedor DO jogo de ${canon}`, exact: true });
  await expect(remove).toBeVisible();
  await expect(page.getByRole("button", { name: `Remover alias Vencedor do jogo de ${canon}`, exact: true })).toHaveCount(0);
  expect(await prisma.mercadoAlias.count({ where: { mercadoPadraoId: market.id } })).toBe(1);
  await remove.click();
  await expect(remove).toHaveCount(0);
  expect(await prisma.mercadoAlias.count({ where: { mercadoPadraoId: market.id } })).toBe(0);
  expect(errors, descreverErros(errors)).toEqual([]);
});
